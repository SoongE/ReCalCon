def context_prompt(dataset, n_ctx, augmented):
    table = CONTEXT_AUG if augmented else CONTEXT_CLEAN
    templates = table.get(dataset, table["default"])
    ctx = "X " * n_ctx
    return [t.replace("{ctx}", ctx) for t in templates]


def handcrafted_prompt(dataset, augmented):
    table = HANDCRAFTED_AUG if augmented else HANDCRAFTED_CLEAN
    if dataset not in table:
        raise KeyError(f"no handcrafted {'augmented' if augmented else 'clean'} prompt for '{dataset}'")
    return list(table[dataset])
